# Quest 17: The Endless Staircase
# Concept: while loop - stops when counter reaches 5

print("=== Quest 17: The Endless Staircase ===")
print("Counting up using a while loop:\n")

count = 0

while count < 5:
    print(f"Step {count}")
    count += 1

print(f"\nReached step {count}. The staircase ends here!")
